/**
 * Codegen: bundle the SVG data for every icon referenced in the curated
 * `src/lib/icon-catalog.ts` into `src/lib/chore-icons.generated.ts`, so chore
 * icons render offline (no runtime Iconify API/CDN dependency).
 *
 * Run with `pnpm icons:gen` after editing the catalog. Fails loudly if any
 * catalog ID is missing from the installed icon set.
 *
 * IDs are read from the catalog source via regex (rather than importing the TS
 * module) to keep this a dependency-free plain-node script.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { getIconData } from '@iconify/utils';
import mdi from '@iconify/json/json/mdi.json' with { type: 'json' };

const __dirname = dirname(fileURLToPath(import.meta.url));
const collections = { mdi };

const src = readFileSync(resolve(__dirname, '../src/lib/icon-catalog.ts'), 'utf8');
const ids = [...new Set([...src.matchAll(/iconId:\s*'([^']+)'/g)].map((m) => m[1]))].sort();

const out = {};
const missing = [];

for (const id of ids) {
  const [prefix, name] = id.split(':');
  const collection = collections[prefix];
  const data = collection && name ? getIconData(collection, name) : null;
  if (!data) {
    missing.push(id);
    continue;
  }
  out[id] = {
    body: data.body,
    width: data.width ?? collection.width ?? 24,
    height: data.height ?? collection.height ?? 24,
  };
}

if (missing.length > 0) {
  console.error(`✗ ${missing.length} catalog icon(s) not found:\n  ${missing.join('\n  ')}`);
  process.exit(1);
}

const file = `// AUTO-GENERATED by scripts/gen-chore-icons.mjs — do not edit by hand.
// Run \`pnpm icons:gen\` to regenerate after changing src/lib/icon-catalog.ts.
import type { IconifyIcon } from '@iconify/types';

export const ICON_DATA: Record<string, IconifyIcon> = ${JSON.stringify(out, null, 2)};
`;

writeFileSync(resolve(__dirname, '../src/lib/chore-icons.generated.ts'), file);
console.log(`✓ Generated ${Object.keys(out).length} chore icons → src/lib/chore-icons.generated.ts`);
